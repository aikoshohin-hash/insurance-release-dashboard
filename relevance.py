"""関連性ゲート — 「商品ニュースか否か」を先に決める層

v3 までは KEYWORDS_JA = ["販売","発売","取扱","開始","改定"] の
部分一致だけで拾っていたため、「CM放映開始」「創作四字熟語募集開始」
「奨学金の募集開始」までが同じ土俵に並んでいた。

v4 の考え方:
  スコアリングの前に **3値の分類** を行い、本線・周辺・除外を分ける。
  判定は必ず理由文字列を伴い、除外されたものも捨てずに残す
  （ダッシュボードの「除外ログ」タブで人が検証できるようにするため）。

  PRODUCT    本線。保険商品そのものの発売・改定・停止・利率変更
  PERIPHERAL 周辺。商品ではないが商品事業に関係する（非保険ソリューション、
             チャネル提携、事務サービス、実証実験など）
  EXCLUDE    ノイズ。広報・CSR・人事・IR・災害対応・システム保守

分類の順序が重要:
  1. HARD_EXCLUDE を最初に見る（「新CM…の放映開始」は "開始" を含むため）
  2. 次に PRODUCT_ACTION（複合語のみ。裸の「開始」「販売」「取扱」は不可）
  3. 次に PERIPHERAL
  4. どれにも当たらなければ EXCLUDE（= 商品アクション語が無い）

裸の「開始」を主キーワードから外したことが、v3 との最大の違い。
"""

from __future__ import annotations

import re

TIER_PRODUCT    = "PRODUCT"
TIER_PERIPHERAL = "PERIPHERAL"
TIER_EXCLUDE    = "EXCLUDE"

TIER_ORDER = {TIER_PRODUCT: 0, TIER_PERIPHERAL: 1, TIER_EXCLUDE: 2}


# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
#  1. HARD_EXCLUDE — 商品アクション語を含んでいても捨てる
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
#  (正規表現, 除外カテゴリ)
#  実データ(2025/10〜2026/09 の113件)で観測されたノイズを網羅する。
