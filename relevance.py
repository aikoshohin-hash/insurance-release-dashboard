    # ── CSR・社会貢献 ──
    (r"寄付|義援金|募金|チャリティ|ボランティア",             "CSR・寄付"),
    (r"(作品|エッセイ|川柳|写真|標語|論文).{0,6}募集",        "CSR・公募"),
